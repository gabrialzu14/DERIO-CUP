const {chromium,devices}=require('playwright');
const ok=(c,m)=>console.log((c?'PASS ':'FAIL ')+m);
(async()=>{const b=await chromium.launch();
const ctx=await b.newContext({...devices['Pixel 5'],serviceWorkers:'allow'});const p=await ctx.newPage();
const errs=[];p.on('pageerror',e=>errs.push(e.message));
let bytes=0,reqs=0;p.on('response',async r=>{reqs++;try{const l=r.headers()['content-length'];if(l)bytes+=+l}catch{}});
await p.route('**/derio_cup_results*',r=>r.fulfill({status:200,contentType:'application/json',body:JSON.stringify([{match_id:'2015-grupo-A-1015-c1',home_score:2,away_score:1}])}));
await p.route('**/derio_cup_fans*',r=>r.fulfill({status:200,contentType:'application/json',body:'[]'}));
await p.goto('http://localhost:3100/',{waitUntil:'networkidle'});await p.waitForTimeout(1500);
const sw=await p.evaluate(async()=>{const r=await navigator.serviceWorker.getRegistration();return !!(r&&(r.active||r.installing||r.waiting))});
ok(sw,'service worker registrado');
await p.evaluate(()=>{localStorage.setItem('derio-cup-tournament','2015');localStorage.setItem('derio-cup-lang','es');localStorage.setItem('derio-cup-onboarded','1');localStorage.setItem('derio-cup-team:2015','derio')});
await p.goto('http://localhost:3100/#partidos',{waitUntil:'networkidle'});await p.waitForTimeout(1500);
await p.goto('http://localhost:3100/',{waitUntil:'networkidle'});await p.waitForTimeout(1200);
console.log('1ª carga completa: ~',Math.round(bytes/1024),'KB declarados,',reqs,'peticiones');
// SIN CONEXIÓN
await ctx.setOffline(true);
await p.route('**/derio_cup_results*',r=>r.abort());
await p.reload({waitUntil:'domcontentloaded'}).catch(e=>console.log('reload error',e.message.slice(0,80)));
await p.waitForTimeout(2500);
ok(await p.locator('.tabbar').count()===1,'sin conexión: la app abre');
ok(await p.locator('.banner').count()===1,'sin conexión: aviso');
const crests=await p.evaluate(()=>[...document.images].filter(i=>i.complete&&i.naturalWidth>0).length);
ok(crests>=4,'sin conexión: escudos visibles ('+crests+')');
await p.evaluate(()=>{location.hash='#partidos'});await p.waitForTimeout(600);const score=await p.locator('.match-row .score').first().innerText().catch(()=>'-');
ok(/2\s*[–-]\s*1/.test(score),'sin conexión: últimos resultados guardados ('+score.replace(/\n/g,'')+')');
await p.goto('http://localhost:3100/#clasificacion').catch(()=>{});await p.waitForTimeout(800);
ok(await p.locator('.table-card').count()===1,'sin conexión: navegar entre pestañas');
console.log('errs',errs.filter(e=>!/Failed to fetch|NetworkError|ERR_/.test(e)));
await b.close();})();
